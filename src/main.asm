; ------------------------------------------------------
; Copy ASCIIZ HL->DE including the NUL, up to B-1 chars then forced NUL.
STRCPYN
.l
	LD		A, B
	CP		1
	JR		Z, .term
	LD		A, (HL)
	LD		(DE), A
	OR		A
	RET		Z
	INC		HL
	INC		DE
	DEC		B
