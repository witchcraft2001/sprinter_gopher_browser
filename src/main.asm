; ------------------------------------------------------
; Single-line text input on the status row (used for type-7 search and Ctrl+G).
; In:  HL = prompt ASCIIZ, DE = destination buffer, B = buffer size (incl. NUL).
; Out: CF=0 submitted (Enter), CF=1 cancelled (Esc). Buffer is ASCIIZ either way.
; Uses ScanKey (A=char code, E=ASCII) with a wait-for-release debounce so a held
; key registers once. The caller supplies an ASCIIZ initial value (empty for a
; fresh prompt); the buffer is kept NUL-terminated as it is edited.
; ------------------------------------------------------
INPUT_LINE
	LD		(in_prompt), HL
	LD		(in_buf), DE
	LD		A, B
	DEC		A						; reserve one byte for the NUL
	LD		(in_max), A
	LD		HL, DE
	CALL	UTIL.STRLEN
	LD		A, C
	LD		(in_pos), A
	CALL	INP_WAIT_RELEASE		; don't read the Enter that opened the prompt
.redraw
	CALL	INP_DRAW
.poll
	CALL	CLOCK_TICK				; keep the clock live while typing
	CALL	KBD.SCAN
	JR		Z, .poll
	CP		KEY_ENTER
	JR		Z, .submit
	CP		KEY_ESC
	JR		Z, .cancel
	CP		KEY_BS
	JR		Z, .back
	LD		A, E					; ASCII; accept printable 0x20..0x7E only
	CP		0x20
	JR		C, .ignore
	CP		0x7F
	JR		NC, .ignore
	LD		A, (in_pos)
	LD		HL, in_max
	CP		(HL)
	JR		Z, .ignore				; buffer full
	LD		HL, (in_buf)
	LD		C, A					; A = in_pos
	LD		B, 0
	ADD		HL, BC
	LD		A, E
	LD		(HL), A					; store the char
	INC		HL
	XOR		A
	LD		(HL), A					; keep it NUL-terminated
	LD		HL, in_pos
	INC		(HL)
	CALL	INP_WAIT_RELEASE
	JR		.redraw
.back
	LD		A, (in_pos)
	OR		A
	JR		Z, .ignore				; nothing to erase
	DEC		A
	LD		(in_pos), A
	LD		HL, (in_buf)
	LD		C, A
	LD		B, 0
	ADD		HL, BC
	XOR		A
	LD		(HL), A					; truncate
	CALL	INP_WAIT_RELEASE
	JR		.redraw
.ignore
	CALL	INP_WAIT_RELEASE
	JR		.poll
.submit
	CALL	INP_WAIT_RELEASE
	OR		A						; CF=0
	RET
.cancel
	CALL	INP_WAIT_RELEASE
	SCF
	RET

