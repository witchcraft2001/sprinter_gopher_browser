; Launch the program whose command line is in HL (program + args). Saves/restores
; SP (Dss.Exec changes it), re-maps our WIN2 scratch page and re-asserts 80x32 text
; on return (the child may have changed both). Out: A=exit code, CF=1 on launch
; error (FM idiom: HL=cmdline, BC=#0040).
; Clear the screen to the standard attributes (black paper, non-bright white
; ink = ATTR_NORM) and announce the program we are about to launch, so the
; external viewer starts from a clean, predictable console. In: HL = command
; line (lives in the WIN2 page, CFG_CMD_BUF). Preserves HL for the Dss.Exec that
; follows. (PChars prints fine straight from WIN2 - verified on target.)
SHOW_EXEC_BANNER
	PUSH	HL
	CALL	TERM.CLS				; black background, non-bright white text
	LD		DE, 0					; D=row 0, E=col 0
	CALL	TERM.LOCATE
	LD		HL, MSG_RUNEXT			; "Running external viewer:\r\n"
	CALL	TERM.PUTS
	POP		HL
	PUSH	HL						; HL = command line
	CALL	TERM.PUTS				; print the command line straight from WIN2
	LD		HL, MSG_CRLF			; end the line so the child starts on a fresh row
	CALL	TERM.PUTS
	POP		HL						; restore command pointer for Dss.Exec
	RET

EXEC_PROGRAM
	CALL	SHOW_EXEC_BANNER		; clean screen + "Running external viewer:" + cmd
	; Dss.Exec saves the parent's WIN1/WIN2/WIN3 page registers (and SP) and
	; restores them on return; our WIN2 page is a GetMem block tagged to our task,
	; so the child can't allocate over it. So the WIN2 runtime stack survives the
	; exec unchanged - no stack juggling needed. (exec_sp is just belt-and-braces;
	; it's a WIN1 var, valid to read whatever WIN2 holds.)
	LD		(exec_sp), SP
	LD		BC, 0x0040				; B=0 (short name), C=#40 (Dss.Exec)
	RST		DSS						; -> A=exit code, CF=1 error
	LD		SP, (exec_sp)
	PUSH	AF
	CALL	CHDIR_EXE				; cwd is process state (not a window) - restore it
	LD		A, (video_page)			; restore the text-screen page captured at startup
	LD		B, A
	LD		A, DSS_VMOD_T80			; re-assert 80x32 text mode
	LD		C, DSS_SETVMOD
	RST		DSS
	; The child may have used the network itself (or reprogrammed the card
	; directly), so drop our cached "session is up" flag; the next fetch
	; re-runs NET.INIT (best-effort NETDONE + NETINIT on the still-loaded DLL).
	CALL	INVALIDATE_NET
	POP		AF
	RET

; Drop the cached "network session is up" flag (net_inited) so the next fetch
; re-runs NET.INIT: it does not reload/unload the DLL (UNETLD loaded state is
; untouched and l_free is not called), it just repeats NETDONE + NETINIT on the
; backend still resident in WIN1. This is a RECOVERY: a cached net_inited=1
; makes a fetch skip straight to CONNECT and reuse the existing session; if
; that session has gone stale (idle time on a local page, or a child program
; touching the card) the connect can hang, and without this it would never
; recover. Trashes A.
INVALIDATE_NET
	XOR		A
	LD		(net_inited), A
	RET

; Derive an 8.3 filename from the selector DL_SEL into DL_NAME, then build
; DL_PATH = "DOWNLOAD\<name>". Non-FAT chars are sanitised; an empty basename
; falls back to a default. Trashes A/BC/DE/HL.
MAKE_DLNAME
	; 1) find the basename start (after the last '/' or '\') in DE.
	LD		HL, DL_SEL
	LD		D, H
	LD		E, L
.fb
	LD		A, (HL)
	OR		A
	JR		Z, .fbdone
	CP		'/'
	JR		Z, .sep
	CP		'\'
	JR		Z, .sep
	INC		HL
	JR		.fb
.sep
	INC		HL
	LD		D, H
	LD		E, L					; basename start = char after the separator
	JR		.fb
.fbdone
	LD		A, (DE)
	OR		A
	JP		Z, .default				; empty basename
	; 2) copy up to 8 name chars (until '.' or end) into DL_NAME.
	EX		DE, HL					; HL = src basename
	LD		DE, DL_NAME				; dst
	LD		B, 8
.nloop
	LD		A, (HL)
	OR		A
	JR		Z, .namedone			; end, no extension
	CP		'.'
	JR		Z, .extstart
	CALL	SANITIZE_CH
	LD		(DE), A
	INC		DE
	INC		HL
	DJNZ	.nloop
	; name longer than 8: skip the rest until '.' or end
.skipname
	LD		A, (HL)
	OR		A
	JR		Z, .namedone
	CP		'.'
	JR		Z, .extstart
	INC		HL
	JR		.skipname
.extstart
	INC		HL						; skip the '.'
	LD		A, (HL)
	OR		A
	JR		Z, .namedone			; trailing dot, no extension
	LD		A, '.'
	LD		(DE), A
	INC		DE
	LD		B, 3
.eloop
	LD		A, (HL)
	OR		A
	JR		Z, .namedone
	CALL	SANITIZE_CH
	LD		(DE), A
	INC		DE
	INC		HL
	DJNZ	.eloop
.namedone
	XOR		A
	LD		(DE), A					; NUL-terminate DL_NAME
	JR		.buildpath
.default
	LD		HL, DEF_DLNAME
	LD		DE, DL_NAME
	LD		B, 16
	CALL	STRCPYN
.buildpath
	LD		HL, DL_DIRPFX			; "DOWNLOAD\"
	LD		DE, DL_PATH
	CALL	COPYZ					; DE -> end (no NUL)
	LD		HL, DL_NAME
	CALL	COPYZ
	XOR		A
	LD		(DE), A					; NUL-terminate DL_PATH
	RET

; Map A to a FAT-safe uppercase filename char (A-Z 0-9 - _ kept, else '_').
SANITIZE_CH
	CP		'a'
	JR		C, .chk
	CP		'z' + 1
	JR		NC, .chk
	SUB		0x20					; to uppercase
.chk
	CP		'0'
	JR		C, .bad
	CP		'9' + 1
	JR		C, .good
	CP		'A'
	JR		C, .bad
	CP		'Z' + 1
	JR		C, .good
	CP		'-'
	RET		Z
	CP		'_'
	RET		Z
.bad
	LD		A, '_'
.good
	RET

; ------------------------------------------------------
; Parse LINE_BUF into row_type + p_disp/p_sel/p_host/p_port (pointers into
; LINE_BUF). TABs are replaced with NUL; absent fields point at an empty string.
; ------------------------------------------------------
PARSE_ROW
	LD		DE, EMPTYSTR
	LD		(p_sel), DE
	LD		(p_host), DE
	LD		(p_port), DE
	LD		A, (DOC_TYPE_CUR)
	CP		'1'
	JR		Z, .menu
	; text document (type 0): the line is raw text, NO type byte and no TAB
	; fields - the whole line is the display.
	LD		HL, LINE_BUF
	LD		(p_disp), HL
	XOR		A
	LD		(row_type), A			; 0 = plain text line (non-selectable)
	RET
.menu
	LD		HL, LINE_BUF
	LD		A, (HL)
	LD		(row_type), A
	INC		HL
	LD		(p_disp), HL
	CALL	SCAN_FIELD				; end of display
	RET		NC						; info line: no further fields
	LD		(p_sel), HL
	CALL	SCAN_FIELD
	RET		NC
	LD		(p_host), HL
	CALL	SCAN_FIELD
	RET		NC
	LD		(p_port), HL
	; gopher+ servers (e.g. nihirash.net) append a 5th "\t+" field after the port
	; to flag gopher+ support. Terminate the port field too so it does not inherit
	; that "\t+" tail - otherwise PORT_CUR becomes "70\t+", NET.CONNECT's port
	; argument is malformed, and every link on such a menu fails to connect. (For
	; a normal menu the port is the last field: SCAN_FIELD hits the line NUL and
	; changes nothing.)
	CALL	SCAN_FIELD
	RET

; Advance HL to the next field. If a TAB is found it is replaced with NUL and
; HL points past it (CF=1); at NUL, CF=0 (no more fields).
SCAN_FIELD
.l
	LD		A, (HL)
	OR		A
	JR		Z, .end
	CP		9
	JR		Z, .tab
	INC		HL
	JR		.l
.tab
	LD		(HL), 0
	INC		HL
	SCF
	RET
.end
	OR		A
	RET

; ------------------------------------------------------
; History: push current nav before following a link; pop to go back.
; ------------------------------------------------------
PUSH_HIST
	LD		A, (hist_sp)
	CP		HIST_MAX
	JR		C, .haveroom
	; full: free the oldest level's cached pages, then shift the array down
	LD		HL, HIST_DATA + HR_DOCSTATE
	CALL	DOC.FREE_STATE
	LD		HL, HIST_DATA + HR_SIZE
	LD		DE, HIST_DATA
	LD		BC, (HIST_MAX - 1) * HR_SIZE
	LDIR
	LD		A, HIST_MAX - 1
	LD		(hist_sp), A
.haveroom
	LD		A, (hist_sp)
	CALL	HREC_ADDR				; HL = record address
	PUSH	HL
	LD		A, (cur_kind)
	LD		(HL), A					; +HR_KIND
	POP		HL
	PUSH	HL
	LD		DE, HR_HOST
	ADD		HL, DE
	EX		DE, HL
	LD		HL, HOST_CUR
	LD		B, 64
	CALL	STRCPYN
	POP		HL
	PUSH	HL
	LD		DE, HR_PORT
	ADD		HL, DE
	EX		DE, HL
	LD		HL, PORT_CUR
	LD		B, 8
	CALL	STRCPYN
	POP		HL
	PUSH	HL
	LD		DE, HR_SEL
	ADD		HL, DE
	EX		DE, HL
	LD		HL, SEL_CUR
	LD		B, 200
	CALL	STRCPYN
	POP		HL
	PUSH	HL
	LD		DE, HR_TYPE
	ADD		HL, DE
	LD		A, (DOC_TYPE_CUR)
	LD		(HL), A
	POP		HL
	PUSH	HL
	LD		DE, HR_SELIDX
	ADD		HL, DE
	EX		DE, HL
	LD		HL, (sel_index)
	CALL	STORE_HL_DE
	POP		HL
	LD		DE, HR_TOPIDX
	ADD		HL, DE
	EX		DE, HL
	LD		HL, (top_index)
	CALL	STORE_HL_DE
	; title
	LD		A, (hist_sp)
	CALL	HREC_ADDR
	LD		DE, HR_TITLE
	ADD		HL, DE
	EX		DE, HL
	LD		HL, DOC_TITLE
	LD		B, TITLE_MAX
	CALL	STRCPYN
	; cache the document itself (page chain) so Back needs no re-fetch
	LD		A, (hist_sp)
	CALL	HREC_ADDR
	LD		DE, HR_DOCSTATE
	ADD		HL, DE
	CALL	DOC.SAVE_STATE
	LD		A, (hist_sp)
	INC		A
	LD		(hist_sp), A
	RET

POP_HIST
	LD		A, (hist_sp)
	OR		A
	RET		Z
	DEC		A
	LD		(hist_sp), A
	CALL	HREC_ADDR				; HL = record
	PUSH	HL
	LD		A, (HL)
	LD		(cur_kind), A
	POP		HL
	PUSH	HL
	LD		DE, HR_HOST
	ADD		HL, DE
	LD		DE, HOST_CUR
	LD		B, 64
	CALL	STRCPYN
	POP		HL
	PUSH	HL
	LD		DE, HR_PORT
	ADD		HL, DE
	LD		DE, PORT_CUR
	LD		B, 8
	CALL	STRCPYN
	POP		HL
	PUSH	HL
	LD		DE, HR_SEL
	ADD		HL, DE
	LD		DE, SEL_CUR
	LD		B, 200
	CALL	STRCPYN
	POP		HL
	PUSH	HL
	LD		DE, HR_TYPE
	ADD		HL, DE
	LD		A, (HL)
	LD		(DOC_TYPE_CUR), A
	POP		HL
	PUSH	HL
	LD		DE, HR_SELIDX
	ADD		HL, DE
	CALL	LOAD_HL_FROM_HL
	LD		(sel_index), HL
	POP		HL
	PUSH	HL
	LD		DE, HR_TOPIDX
	ADD		HL, DE
	CALL	LOAD_HL_FROM_HL
	LD		(top_index), HL
	POP		HL
	LD		DE, HR_TITLE
	ADD		HL, DE
	LD		DE, DOC_TITLE
	LD		B, TITLE_MAX
	CALL	STRCPYN
	; restore the cached document (page chain) - no re-fetch
	LD		A, (hist_sp)
	CALL	HREC_ADDR
	LD		DE, HR_DOCSTATE
	ADD		HL, DE
	CALL	DOC.LOAD_STATE
	RET

; HL = HIST_DATA + A*HR_SIZE
HREC_ADDR
	LD		HL, HIST_DATA
	OR		A
	RET		Z
	LD		B, A
	LD		DE, HR_SIZE
.l
	ADD		HL, DE
	DJNZ	.l
	RET

; Store HL (16-bit little-endian) at (DE).
STORE_HL_DE
	LD		A, L
	LD		(DE), A
	INC		DE
	LD		A, H
	LD		(DE), A
	RET

; Load 16-bit little-endian from (HL) into HL.
LOAD_HL_FROM_HL
	LD		A, (HL)
	INC		HL
	LD		H, (HL)
	LD		L, A
	RET

